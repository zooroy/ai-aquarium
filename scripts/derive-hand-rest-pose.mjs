import { readFile, writeFile } from 'node:fs/promises';
import { parseGlb, deriveRest, preprocess, encodeGlb } from './hand-model.mjs';
const models=parseGlb(await readFile(new URL('../public/models/low-poly-hands.glb',import.meta.url)));
const rest=deriveRest(models), processed=models.map((model,i)=>preprocess(model,rest[i]));
for(let i=0;i<processed.length;i++) {
  rest[i].fallback=processed[i].fallback;
  console.log(`${rest[i].name} (${rest[i].hand}): ${processed[i].faces.length} triangles; ring vertices ${processed[i].rings.map(r=>r.map(x=>x.vertices.length).join('/')).join(', ')}; two-bone fallback: ${rest[i].fallback.join(', ')||'none'}`);
}
await writeFile(new URL('../public/models/low-poly-hands.rigged.glb',import.meta.url),encodeGlb(processed));
await writeFile(new URL('../src/render/hand/hand-rest-pose.ts',import.meta.url),`// Generated by scripts/derive-hand-rest-pose.mjs; model coordinates, no surface displacement.\nexport const HAND_REST_POSES = ${JSON.stringify(rest,null,2)} as const;\n`);
